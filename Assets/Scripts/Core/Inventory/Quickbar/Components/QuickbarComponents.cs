using Unity.Entities;

/// <summary>
/// Компонент, хранящий индекс активного слота квикбара (0-7).
/// <para>
/// Это чистое "состояние намерения" игрока. Оно изменяется системой QuickbarSelectionSystem
/// в ответ на ввод (нажатие цифр, скролл). Другие системы читают этот индекс, чтобы
/// определить, с каким слотом инвентаря нужно работать.
/// </para>
/// </summary>
public struct ActiveQuickbarSlot : IComponentData
{
    /// <summary>
    /// Индекс выбранного слота, от 0 до 7.
    /// </summary>
    public int Index;
}

/// <summary>
/// Компонент, хранящий ID предмета, который в данный момент "экипирован"
/// (находится в активном слоте квикбара).
/// <para>
/// Это производные данные, которые синхронизируются системой ActiveItemSystem. Она смотрит
/// на ActiveQuickbarSlot и реальное содержимое инвентаря, чтобы этот компонент всегда
/// отражал правду. Если в активном слоте нет предмета, этот компонент удаляется.
/// Системы игровой логики (бой, строительство) должны реагировать именно на этот компонент.
/// </para>
/// </summary>
public struct ActiveEquippedItem : IComponentData
{
    /// <summary>
    /// Уникальный ID предмета из ItemRegistry.
    /// </summary>
    public int ItemID;
}